-- Snowflake version of the warehouse schema (equivalent to sql/schema.sql).
-- Not executed in CI; provided for deployment to Snowflake.
-- Snowflake does not enforce PRIMARY KEY / UNIQUE, so idempotency is handled with MERGE (see load.sql).

CREATE SCHEMA IF NOT EXISTS TELEMETRY;
USE SCHEMA TELEMETRY;

CREATE TABLE IF NOT EXISTS RAW_LOGS (
    PAYLOAD     VARIANT,
    SOURCE_FILE STRING,
    LOADED_AT   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS DIM_SERVICE (
    SERVICE_KEY  NUMBER AUTOINCREMENT PRIMARY KEY,
    SERVICE_NAME STRING NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS DIM_ENDPOINT (
    ENDPOINT_KEY  NUMBER AUTOINCREMENT PRIMARY KEY,
    SERVICE_KEY   NUMBER NOT NULL REFERENCES DIM_SERVICE(SERVICE_KEY),
    ENDPOINT_PATH STRING NOT NULL
);

CREATE TABLE IF NOT EXISTS DIM_DATE (
    DATE_KEY      NUMBER PRIMARY KEY,
    CALENDAR_DATE DATE NOT NULL,
    DAY_OF_WEEK   NUMBER NOT NULL
);

CREATE TABLE IF NOT EXISTS FACT_REQUEST (
    EVENT_ID     STRING PRIMARY KEY,
    DATE_KEY     NUMBER NOT NULL,
    EVENT_HOUR   NUMBER NOT NULL,
    ENDPOINT_KEY NUMBER NOT NULL,
    STATUS_CODE  NUMBER NOT NULL,
    IS_GOOD      BOOLEAN NOT NULL,
    DURATION_MS  FLOAT NOT NULL,
    TRACE_ID     STRING,
    LOADED_AT    TIMESTAMP_NTZ NOT NULL
)
CLUSTER BY (DATE_KEY);

CREATE TABLE IF NOT EXISTS SLO_TARGET (
    SERVICE_NAME      STRING PRIMARY KEY,
    AVAILABILITY_SLO  FLOAT NOT NULL,
    LATENCY_SLO_MS    FLOAT NOT NULL,
    LATENCY_SLO_SHARE FLOAT NOT NULL
);
